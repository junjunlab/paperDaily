export type Dict = typeof ZH

export const dict = (lang: Lang): Dict => (lang === 'en' ? EN : ZH)

/** 时间范围选项：d3 / d7 / d30 用「近 N 天」的说法 */
export const rangeOptions = (lang: Lang) =>
  lang === 'en'
    ? [
        { key: 'today', name: 'Today' },
        { key: 'd3', name: '3 days' },
        { key: 'd7', name: '7 days' },
        { key: 'd30', name: '30 days' },
      ]
    : [
        { key: 'today', name: '今天' },
        { key: 'd3', name: '3天' },
        { key: 'd7', name: '7天' },
        { key: 'd30', name: '30天' },
      ]

/** 时间窗的「往前天数」：3天 = 今天 + 前 2 天（共 3 个日历日） */
export const rangeDays = (key: string): number =>
  ({ today: 0, d3: 2, d7: 6, d30: 29 }[key] ?? 0)
